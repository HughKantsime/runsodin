import { fetchAPI } from './client'

export interface DispatchStatus {
  job_id: number
  phase: 'unconfirmed' | 'target_busy' | 'preparing' | 'sending' | 'start_accepted' | 'needs_reconciliation' | 'layer_observed'
  retry_blocked: boolean
  observation: { current_layer: number | null; total_layers: number | null; progress_percent: number | null; status: string; start_observation_age_seconds: number } | null
}
export interface DispatchConfirmation {
  confirmation: 'accepted' | 'unconfirmed'
  status?: DispatchStatus
}

/** A lost POST response cannot authorize another POST. Reconcile using GET only. */
export async function dispatchWithConfirmation(id: number): Promise<DispatchConfirmation> {
  let validationError: unknown
  try {
    const response = await fetchAPI<{success: boolean; job_id: number}>(`/jobs/${id}/dispatch`, { method: 'POST' })
    if (response?.success === true && response.job_id === id) return { confirmation: 'accepted' }
  } catch (error) {
    const code = (error as Error & {status?: number}).status
    // 408 can be generated by an intermediary while the sender continues.
    if (code && code >= 400 && code < 500 && code !== 408 && code !== 400) throw error
    // Existing server 400 responses can also describe an uncertain adapter result.
    if (code === 400) validationError = error
  }
  try {
    const status = await fetchAPI<DispatchStatus>(`/jobs/${id}/dispatch-status`)
    if (status?.job_id === id && status.retry_blocked === true) {
      if (validationError && status.phase === 'unconfirmed') throw validationError
      return { confirmation: 'unconfirmed', status }
    }
  } catch (error) {
    if (error === validationError && validationError) throw error
    // Original transport uncertainty survives a failed reconciliation.
  }
  return { confirmation: 'unconfirmed' }
}
