test('support bundle refuses duplicate requests while pending and reports a retryable failure',async()=>{
 let reject!:(reason:Error)=>void
 state.download.mockImplementationOnce(()=>new Promise((_,no)=>{reject=no}))
 client(<SystemTab/>,'/settings')
 fireEvent.click(screen.getByRole('button',{name:'Download support bundle'}))
 const pending=screen.getByRole('button',{name:'Preparing support bundle...'})
 expect(pending).toBeDisabled();fireEvent.click(pending)
 expect(state.download).toHaveBeenCalledOnce()
 reject(new Error('Synthetic generation failed'))
 await screen.findByRole('alert');expect(screen.getByRole('alert')).toHaveTextContent('Synthetic generation failed')
 state.download.mockResolvedValueOnce(undefined)
 fireEvent.click(screen.getByRole('button',{name:'Download support bundle'}))
 await waitFor(()=>expect(state.download).toHaveBeenCalledTimes(2))
 await waitFor(()=>expect(screen.queryByRole('alert')).not.toBeInTheDocument())
})
