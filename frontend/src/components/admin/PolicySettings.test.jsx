import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { ipAllowlist, retention } from '../../api'
import IPAllowlistSettings from './IPAllowlistSettings'
import DataRetentionSettings from './DataRetentionSettings'
vi.mock('../../api', () => ({ ipAllowlist: { get: vi.fn(), set: vi.fn() }, retention: { get: vi.fn(), set: vi.fn(), runCleanup: vi.fn() } }))
beforeEach(() => {
  vi.resetAllMocks()
  retention.set.mockImplementation(async data=>data)
  ipAllowlist.get.mockResolvedValue({ enabled: true, cidrs: [], mode: 'api_and_ui' })
  retention.get.mockResolvedValue({ completed_jobs_days: 30, audit_logs_days: 365, timelapses_days: 60, alert_history_days: 90 })
})
afterEach(cleanup)
it.each([['198.51.100.7','198.51.100.7/32'],['2001:db8:abcd::1','2001:db8:abcd::1/128'],['2001:db8:abcd::/64','2001:db8:abcd::/64']])('adds %s with intended prefix',async(input,expected)=>{
  ipAllowlist.set.mockImplementation(async data=>data)
  render(<IPAllowlistSettings />)
  fireEvent.change(await screen.findByRole('textbox'),{target:{value:input}})
  fireEvent.click(screen.getByRole('button',{name:'Add'}))
  expect(screen.getByText(expected)).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button',{name:'Save'}))
  await waitFor(()=>expect(ipAllowlist.set).toHaveBeenCalledWith(expect.objectContaining({cidrs:[expected]})))
})
it.each([['allowlist',IPAllowlistSettings,ipAllowlist],['retention',DataRetentionSettings,retention]])('refuses unknown %s configuration and offers retry',async(_name,Component,api)=>{
  api.get.mockRejectedValueOnce(new Error('Unavailable'))
  render(<Component />)
  expect(await screen.findByRole('alert')).toHaveTextContent(/Unable to load/)
  expect(screen.queryByRole('button',{name:/^Save/})).not.toBeInTheDocument()
  expect(screen.queryByRole('button',{name:'Run Cleanup Now'})).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button',{name:/Retry/}))
  expect(await screen.findByRole('button',{name:/^Save/})).toBeInTheDocument()
  expect(api.get).toHaveBeenCalledTimes(2)
})
it('does not convert cleared retention to keep forever',async()=>{
  render(<DataRetentionSettings />)
  const inputs=await screen.findAllByRole('spinbutton')
  fireEvent.change(inputs[0],{target:{value:''}})
  fireEvent.click(screen.getByRole('button',{name:'Save Policy'}))
  expect(retention.set).not.toHaveBeenCalled()
  expect(await screen.findByRole('alert')).toHaveTextContent(/nonnegative whole/)
})
it('does not clean while policy save is pending',async()=>{
  retention.set.mockReturnValue(new Promise(()=>{}))
  render(<DataRetentionSettings />)
  fireEvent.click(await screen.findByRole('button',{name:'Save Policy'}))
  expect(screen.getByRole('button',{name:'Run Cleanup Now'})).toBeDisabled()
})

it.each(['-1','1.5','9007199254740992'])('refuses invalid retention draft %s',async(value)=>{
  render(<DataRetentionSettings />)
  const inputs=await screen.findAllByRole('spinbutton')
  fireEvent.change(inputs[0],{target:{value}})
  fireEvent.click(screen.getByRole('button',{name:'Save Policy'}))
  expect(retention.set).not.toHaveBeenCalled()
  expect(await screen.findByRole('alert')).toHaveTextContent(/nonnegative whole/)
})
it('saves explicit zero and blocks cleanup until changed policy is saved',async()=>{
  render(<DataRetentionSettings />)
  const inputs=await screen.findAllByRole('spinbutton')
  fireEvent.change(inputs[0],{target:{value:'0'}})
  expect(screen.getByRole('button',{name:'Run Cleanup Now'})).toBeDisabled()
  fireEvent.click(screen.getByRole('button',{name:'Save Policy'}))
  await waitFor(()=>expect(retention.set).toHaveBeenCalledWith({completed_jobs_days:0,audit_logs_days:365,timelapses_days:60,alert_history_days:90}))
  await waitFor(()=>expect(screen.getByRole('button',{name:'Run Cleanup Now'})).not.toBeDisabled())
})
it('does not call cleanup when confirmation is canceled',async()=>{
  const confirmation=vi.spyOn(window,'confirm').mockReturnValue(false)
  render(<DataRetentionSettings />)
  fireEvent.click(await screen.findByRole('button',{name:'Run Cleanup Now'}))
  expect(confirmation).toHaveBeenCalled()
  expect(retention.runCleanup).not.toHaveBeenCalled()
  confirmation.mockRestore()
})
it('retains dirty draft after failed save and does not report success',async()=>{
  retention.set.mockRejectedValueOnce(new Error('Save unavailable'))
  render(<DataRetentionSettings />)
  const inputs=await screen.findAllByRole('spinbutton')
  fireEvent.change(inputs[0],{target:{value:'45'}})
  fireEvent.click(screen.getByRole('button',{name:'Save Policy'}))
  expect(await screen.findByRole('alert')).toHaveTextContent('Save unavailable')
  expect(inputs[0]).toHaveValue(45)
  expect(screen.queryByText('Retention policy saved')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Run Cleanup Now'})).toBeDisabled()
})

it.each([['allowlist',IPAllowlistSettings,ipAllowlist],['retention',DataRetentionSettings,retention]])('refuses malformed %s loaded policy',async(_name,Component,api)=>{
  api.get.mockResolvedValueOnce({})
  render(<Component />)
  expect(await screen.findByRole('alert')).toHaveTextContent(/Unable to load/)
  expect(screen.queryByRole('button',{name:/^Save/})).not.toBeInTheDocument()
})
it('does not claim saved retention or allow cleanup after malformed response',async()=>{
  retention.set.mockResolvedValueOnce({})
  render(<DataRetentionSettings />)
  fireEvent.click(await screen.findByRole('button',{name:'Save Policy'}))
  expect(await screen.findByRole('alert')).toHaveTextContent(/Unable to verify/)
  expect(screen.queryByText('Retention policy saved')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Run Cleanup Now'})).toBeDisabled()
})
it('refuses edits and duplicate cleanup calls during confirmation and pending transport',async()=>{
  let resolve
  retention.runCleanup.mockReturnValue(new Promise(done=>{resolve=done}))
  render(<DataRetentionSettings />)
  const inputs=await screen.findAllByRole('spinbutton')
  const button=screen.getByRole('button',{name:'Run Cleanup Now'})
  const confirmation=vi.spyOn(window,'confirm').mockImplementation(()=>{
    fireEvent.change(inputs[0],{target:{value:'0'}})
    fireEvent.click(button)
    return true
  })
  fireEvent.click(button)
  fireEvent.click(button)
  expect(inputs[0]).toHaveValue(30)
  expect(retention.runCleanup).toHaveBeenCalledTimes(1)
  expect(confirmation).toHaveBeenCalledTimes(1)
  expect(screen.getByRole('button',{name:'Save Policy'})).toBeDisabled()
  resolve({deleted:{completed_jobs:2}})
  expect(await screen.findByText('completed_jobs: 2 records deleted')).toBeInTheDocument()
  confirmation.mockRestore()
})
it('allows only one save before its response and refuses malformed allowlist save result',async()=>{
  let resolve
  ipAllowlist.set.mockReturnValue(new Promise(done=>{resolve=done}))
  render(<IPAllowlistSettings />)
  const save=await screen.findByRole('button',{name:'Save'})
  fireEvent.click(save);fireEvent.click(save)
  expect(ipAllowlist.set).toHaveBeenCalledTimes(1)
  resolve({})
  expect(await screen.findByRole('alert')).toHaveTextContent(/Unable to verify/)
  expect(screen.queryByText('IP allowlist saved')).not.toBeInTheDocument()
})
it('ignores a pending load after unmount',async()=>{
  let resolve
  retention.get.mockReturnValueOnce(new Promise(done=>{resolve=done}))
  const view=render(<DataRetentionSettings />)
  view.unmount()
  resolve({completed_jobs_days:0,audit_logs_days:365,timelapses_days:30,alert_history_days:90})
  await Promise.resolve()
  expect(retention.set).not.toHaveBeenCalled()
  expect(retention.runCleanup).not.toHaveBeenCalled()
})
