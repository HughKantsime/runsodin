def _schedule(s1, uploaded, kind, body):
    identifier = uploaded['id'] if kind == 'print-files' else uploaded['model_id']
    return s1.client.post(f'/api/{kind}/{identifier}/schedule?printer_id=59', headers=s1.auth(), json=body)


def _start_next(s1, attestation='owner_in_app'):
    suggestion = s1.client.get('/api/printers/59/next-suggestion', headers=s1.auth())
    assert suggestion.status_code == 200, suggestion.text
    body = suggestion.json()
    assert body['job_id'] is not None and body['fingerprint'], body
    response = s1.client.post('/api/printers/59/start-next?wait=true', headers=s1.auth(), json=dict(
        suggested_job_id=body['job_id'], suggestion_fingerprint=body['fingerprint'], request_id=str(uuid.uuid4()),
        bed_clear_confirmed=True, attestation=attestation))
    return body, response


@pytest.mark.parametrize('kind', ['print-files', 'models'])
@pytest.mark.parametrize('raw,mapping,indices,grams', [
    pytest.param(ONE_COLOUR, [{'source_slot': 1, 'target_slot': 2}], [1], [11.49], id='one_colour'),
    pytest.param(TWO_COLOUR, [{'source_slot': 1, 'target_slot': 2}, {'source_slot': 2, 'target_slot': 3}], [1, 2], [2.94, 2.16], id='two_colour'),
])
def test_uploaded_gcode_schedules_with_a_mapping_and_reaches_the_printer(s1, kind, raw, mapping, indices, grams):
    uploaded = s1.upload(raw)
    with s1.engine.connect() as c:
        stored = c.execute(text('SELECT filaments_json,stored_path FROM print_files WHERE id=:id'), {'id': uploaded['id']}).one()
    assert stored[0] == '[]', 'Upload leaves generic Moonraker metadata as it was'
    preview = s1.client.get(f"/api/print-files/{uploaded['id']}?printer_id=59", headers=s1.auth())
    assert preview.status_code == 200, preview.text
    required = preview.json()['ams_preview']['required']
    assert [r['material'] for r in required] == ['PLA'] * len(indices) and [r['slot'] for r in required] == list(range(1, len(indices) + 1))
    assert all(r['color'].startswith('#') for r in required)
    scheduled = _schedule(s1, uploaded, kind, dict(ams_mapping=mapping))
    assert scheduled.status_code == 200, scheduled.text
    job_id = scheduled.json()['job_id']
    with s1.engine.connect() as c:
        job = c.execute(text('SELECT ams_mapping,printer_id,colors_required FROM jobs WHERE id=:id'), {'id': job_id}).one()
        assert c.execute(text('SELECT filaments_json FROM print_files WHERE id=:id'), {'id': uploaded['id']}).scalar_one() == '[]'
    assert json.loads(job[0]) == indices and job[1] == 59
    suggestion, started = _start_next(s1)
    assert suggestion['job_id'] == job_id
    assert started.status_code == 200, started.text
    assert started.json()['state'] == 'dispatched', started.json()
    assert len(s1.device.publishes) == 1
    sent = s1.device.publishes[0]['data']
    assert [m['ams_index'] for m in sent['ams_settings']['ams_box_mapping']] == indices
    copy = next(iter(s1.device.files.values()))
    assert (sent['md5'], sent['filesize']) == (hashlib.md5(copy, usedforsecurity=False).hexdigest(), len(copy))
    assert parse_filament_grams(raw.decode(), len(indices)) == grams


