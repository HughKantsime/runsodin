def test_parsing_is_bounded_and_needs_one_weight_per_filament(tmp_path):
    from modules.printers.kobra_s1 import HEADER_LIMIT, S1Refusal
    head = TWO_COLOUR[:TWO_COLOUR.index(b'; EXECUTABLE_BLOCK_START')]
    assert len(head) < HEADER_LIMIT / 4, 'The real config block sits well inside the bound'
    assert parse_filament_grams('; total filament weight [g] : 1.29', 2) is None
    assert parse_filament_grams('; total filament weight [g] : nan,1', 2) is None
    assert parse_filament_grams('no weight here', 1) is None
    late = tmp_path / 'late.gcode'
