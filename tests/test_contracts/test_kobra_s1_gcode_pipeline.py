@pytest.mark.parametrize('setup,reason', [
    pytest.param('no_mapping', 'missing_material_mapping', id='no_mapping'),
    pytest.param('slot_unbound', 'no_bound_spool', id='mapped_slot_has_no_spool'),
    pytest.param('spool_retired', 'no_bound_spool', id='mapped_spool_is_not_active'),
    pytest.param('foreign_spool', 'no_bound_spool', id='mapped_spool_is_another_orgs'),
    pytest.param('change_pending', 'spool_change_pending', id='spool_change_pending'),
    pytest.param('unreadable_file', 'unknown_material_quantity', id='file_cannot_be_read'),
])
def test_monitor_charges_nothing_when_the_mapping_does_not_resolve(s1, monkeypatch, setup, reason):
    job_id = _job_from_upload(s1, ONE_COLOUR, None if setup == 'no_mapping' else [{'source_slot': 1, 'target_slot': 2}])
    with s1.engine.begin() as c:
        if setup == 'slot_unbound':
            c.execute(text('UPDATE filament_slots SET assigned_spool_id=NULL WHERE printer_id=59 AND slot_number=2'))
        elif setup == 'spool_retired':
            c.execute(text("UPDATE spools SET status='empty' WHERE id=902"))
        elif setup == 'foreign_spool':
            c.execute(text('UPDATE spools SET org_id=2 WHERE id=902'))
        elif setup == 'change_pending':
            c.execute(text('UPDATE filament_slots SET tray_observation=:state WHERE printer_id=59 AND slot_number=2'), {'state': json.dumps({'pending': True})})
        elif setup == 'unreadable_file':
            c.execute(text("UPDATE print_files SET stored_path='/nonexistent/owned.gcode'"))
    assert _monitor_deduct(s1, monkeypatch, job_id, 25.0) is None
    assert _weights(s1) == [100, 100, 100]
    audits = _audits(s1)
    assert len(audits) == 1 and audits[0]['consumption'][0]['reason'] == reason


