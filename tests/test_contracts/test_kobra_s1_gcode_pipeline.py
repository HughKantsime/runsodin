def _bind_spools(s1):
    with s1.engine.begin() as c:
        c.execute(text("INSERT INTO filament_library(id,brand,name,material) VALUES(901,'Synthetic','Test','PLA')"))
        c.execute(text("INSERT INTO spools(id,filament_id,remaining_weight_g,initial_weight_g,org_id,location_printer_id,status) "
                       "VALUES(901,901,100,100,1,59,'active'),(902,901,100,100,1,NULL,'active'),(903,901,100,100,1,NULL,'active')"))
        for slot, spool in ((1, 901), (2, 902), (3, 903)):
            c.execute(text('UPDATE filament_slots SET assigned_spool_id=:spool WHERE printer_id=59 AND slot_number=:slot'), {'spool': spool, 'slot': slot})


def _job_from_upload(s1, raw, mapping, model='Kobra S1'):
    uploaded = s1.upload(raw)
    _bind_spools(s1)
    with s1.engine.begin() as c:
        c.execute(text('UPDATE printers SET model=:model WHERE id=59'), {'model': model})
    scheduled = _schedule(s1, uploaded, 'print-files', {} if mapping is None or model != 'Kobra S1' else dict(ams_mapping=mapping))
    assert scheduled.status_code == 200, scheduled.text
    job_id = scheduled.json()['job_id']
    with s1.engine.begin() as c:
        c.execute(text("UPDATE jobs SET status='printing' WHERE id=:id"), {'id': job_id})
    return job_id


def _weights(s1):
    with s1.engine.connect() as c:
        return c.execute(text('SELECT remaining_weight_g FROM spools WHERE id IN (901,902,903) ORDER BY id')).scalars().all()


def _audits(s1):
    with s1.engine.connect() as c:
        rows = c.execute(text("SELECT details FROM audit_logs WHERE action='filament.unattributed'")).scalars().all()
    return [row if isinstance(row, dict) else json.loads(row) for row in rows]


