def test_wire_validation_accepts_real_facts_and_rejects_tampering():
    facts = threemf_parser.plate_facts_from_archive(archive({
        'Metadata/slice_info.config': slice_info(plate_xml(1, 5, 1, FILAMENTS, WARNING)), 'Metadata/plate_1.png': png()}))
    status, decoded = plate_cache.validate_wire({'status': 'ok', **facts})
    assert status == 'ok' and decoded['plates'][0]['thumbnail'] == ('png', png())
    wire = {'status': 'ok', **facts}
    junk = base64.b64encode(b'junk').decode()
    tampered = [
        {**wire, 'extra': 1},
        {**wire, 'plates': [{**facts['plates'][0], 'thumbnail_b64': junk}]},
        {**wire, 'plates': [{**facts['plates'][0], 'thumbnail_b64': '!!!not-base64'}]},
        {**wire, 'plates': [{**facts['plates'][0], 'index': 0}]},
        {**wire, 'plates': [{**facts['plates'][0], 'index': True}]},
        {**wire, 'plates': [{**facts['plates'][0], 'weight_grams': float('inf')}]},
        {**wire, 'plates': [facts['plates'][0], facts['plates'][0]]},
        {**wire, 'plates': facts['plates'] * (threemf_parser.MAX_FACT_PLATES + 1)},
        {'status': 'weird'}, {'status': 'bad_zip', 'extra': 1}, 'text', None,
    ]
    for item in tampered:
        assert plate_cache.validate_wire(item) == ('failed', None), item
    assert plate_cache.validate_wire({'status': 'bad_zip'}) == ('bad_zip', None)


@pytest.fixture
def cache_root(tmp_path, monkeypatch):
    root = tmp_path / 'plate_cache'
    monkeypatch.setenv('PLATE_CACHE_ROOT', str(root))
    return root


def decoded_facts(extra=None):
    members = {'Metadata/slice_info.config': slice_info(plate_xml(1, 5, 1, FILAMENTS), plate_xml(2, 6, 2)),
               'Metadata/plate_1.png': png(), **(extra or {})}
    status, decoded = plate_cache.validate_wire({'status': 'ok', **threemf_parser.plate_facts_from_archive(archive(members))})
    assert status == 'ok'
    return decoded


def test_store_and_read_roundtrip_with_private_permissions(cache_root):
    digest = hashlib.sha256(b'roundtrip').hexdigest()
    document = plate_cache.store(digest, decoded_facts({'Metadata/plate_2.png': jpeg()}))
    assert plate_cache.read_facts(digest) == document
    assert set(document) == {'version', 'file_hash', 'slicer', 'plate_count', 'plates'}
    assert set(document['plates'][0]) == {'index', 'has_thumbnail', 'filaments', 'print_time_seconds',
                                          'weight_grams', 'layer_height', 'warnings'}
    first, second = plate_cache.read_thumbnail(digest, 1), plate_cache.read_thumbnail(digest, 2)
    assert (first.content, first.media_type) == (png(), 'image/png')
    assert second.media_type == 'image/jpeg' or second is None  # a 16px JPEG passes the shared checks
    entry = cache_root / digest[:2] / digest
    assert sorted(os.listdir(entry)) == ['facts.json', 'plate_1.png', 'plate_2.jpg']
    for directory in (cache_root, cache_root / digest[:2], entry):
        assert stat.S_IMODE(os.stat(directory).st_mode) == 0o700
    for name in os.listdir(entry):
        assert stat.S_IMODE(os.stat(entry / name).st_mode) == 0o600
    assert plate_cache.read_thumbnail(digest, 3) is None


def test_bad_hash_and_plate_refused_before_touching_disk(cache_root):
    digest = hashlib.sha256(b'x').hexdigest()
    decoded = decoded_facts()
    for bad in ('../../etc/passwd', 'A' * 64, 'a' * 63, 'a' * 65, '', None, 5, 'a' * 63 + '/', 'g' * 64, 'a' * 64 + '\n'):
        with pytest.raises(ValueError):
            plate_cache.entry_dir(bad)
        with pytest.raises(ValueError):
            plate_cache.store(bad, decoded)
        assert plate_cache.read_facts(bad) is None and plate_cache.read_thumbnail(bad, 1) is None
    assert not cache_root.exists()
    plate_cache.store(digest, decoded)
    for bad_plate in (0, -1, 10000, True, '1', None, 1.0, '../1'):
        assert plate_cache.read_thumbnail(digest, bad_plate) is None


def test_write_is_atomic_and_leaves_no_temporary_files(cache_root, monkeypatch):
    digest = hashlib.sha256(b'atomic').hexdigest()
    real_replace = os.replace

    def failing(source, destination):
        if str(destination).endswith('facts.json'):
            raise OSError('disk full')
        return real_replace(source, destination)
    monkeypatch.setattr(os, 'replace', failing)
    with pytest.raises(OSError):
        plate_cache.store(digest, decoded_facts())
    monkeypatch.undo()
    assert plate_cache.read_facts(digest) is None
    assert sorted(os.listdir(cache_root / digest[:2] / digest)) == ['plate_1.png']


def test_corrupt_or_foreign_facts_are_treated_as_absent(cache_root):
    digest, other = hashlib.sha256(b'a').hexdigest(), hashlib.sha256(b'b').hexdigest()
    plate_cache.store(digest, decoded_facts())
    facts_path = cache_root / digest[:2] / digest / 'facts.json'
    facts_path.write_bytes(b'{not json')
    assert plate_cache.read_facts(digest) is None
    plate_cache.store(digest, decoded_facts())
    (cache_root / other[:2]).mkdir(exist_ok=True)
    os.replace(cache_root / digest[:2] / digest, cache_root / other[:2] / other)   # facts name another hash
    assert plate_cache.read_facts(other) is None


def test_store_analysis_swallows_cache_failures(cache_root, monkeypatch):
    digest = hashlib.sha256(b'swallow').hexdigest()

    def failing(*args, **kwargs):
        raise OSError('read-only file system')
    monkeypatch.setattr(plate_cache, 'store', failing)
    assert plate_cache.store_analysis(digest, SimpleNamespace(status='ok', facts=decoded_facts())) is None
    assert plate_cache.store_analysis(digest, SimpleNamespace(status='failed', facts=None)) is None


def three_plate_package():
    return package_bytes({
        'Metadata/slice_info.config': slice_info(plate_xml(1, 100, 1, FILAMENTS), plate_xml(2, 200, 2), plate_xml(3, 300, 3)),
        'Metadata/plate_1.png': png((250, 0, 0)), 'Metadata/plate_2.png': png((0, 250, 0)), 'Metadata/plate_3.png': png((0, 0, 250)),
        'Metadata/plate_1.gcode': b'; BambuStudio 02.05.00.66\nG28\n', 'Metadata/plate_2.gcode': b'G28\n',
        'Metadata/plate_3.gcode': b'G28\n',
    })


def test_backfill_from_stored_blob_and_eligibility(cache_root, tmp_path, monkeypatch):
    payload = three_plate_package()
    blob = tmp_path / 'stored.3mf'
    blob.write_bytes(payload)
    digest = hashlib.sha256(payload).hexdigest()
    row = SimpleNamespace(file_hash=digest, stored_path=str(blob), blob_state='present')
    facts = plate_cache.facts_for_row(row)
    assert facts['plate_count'] == 3 and facts['slicer'] == {'name': 'BambuStudio', 'version': '02.05.00.66'}
    assert plate_cache.read_facts(digest) == facts
    assert plate_cache.thumbnail_for_row(row, 3).content == png((0, 0, 250))

    from modules.models_library import mesh_isolation

    def forbidden(*args, **kwargs):
        raise AssertionError('a cached file must not be parsed again')
    monkeypatch.setattr(mesh_isolation, 'plate_facts_blocking', forbidden)
    assert plate_cache.facts_for_row(row) == facts
    # No hash, wrong extension or a purged blob: no cache is served, even though one exists for the hash.
    for ineligible in (SimpleNamespace(file_hash=None, stored_path=str(blob), blob_state='present'),
                       SimpleNamespace(file_hash=digest, stored_path=str(blob) + '.gcode', blob_state='present'),
                       SimpleNamespace(file_hash=digest, stored_path=None, blob_state='present'),
                       SimpleNamespace(file_hash=digest, stored_path=str(blob), blob_state='purged')):
        assert plate_cache.facts_for_row(ineligible) is None and plate_cache.thumbnail_for_row(ineligible, 1) is None


def test_backfill_refuses_a_blob_that_does_not_match_its_hash(cache_root, tmp_path):
    blob = tmp_path / 'stored.3mf'
    blob.write_bytes(three_plate_package())
    wrong = hashlib.sha256(b'some other file').hexdigest()
    row = SimpleNamespace(file_hash=wrong, stored_path=str(blob), blob_state='present')
    assert plate_cache.facts_for_row(row) is None
    assert plate_cache.read_facts(wrong) is None


def test_unparseable_blob_is_marked_so_it_is_not_reparsed(cache_root, tmp_path, monkeypatch):
    junk = b'this is not a zip archive'
    blob = tmp_path / 'junk.3mf'
    blob.write_bytes(junk)
    digest = hashlib.sha256(junk).hexdigest()
    row = SimpleNamespace(file_hash=digest, stored_path=str(blob), blob_state='present')
    assert plate_cache.facts_for_row(row) is None
    assert plate_cache.is_unavailable(digest) and plate_cache.read_facts(digest) is None
    from modules.models_library import mesh_isolation
    monkeypatch.setattr(mesh_isolation, 'plate_facts_blocking',
                        lambda *a, **k: (_ for _ in ()).throw(AssertionError('reparsed')))
    assert plate_cache.facts_for_row(row) is None
