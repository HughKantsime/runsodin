import hashlib
from types import SimpleNamespace

import pytest
from modules.models_library.plate_cache import facts_result
from modules.models_library.threemf_parser import MAX_GCODE_HEADER_BYTES


@pytest.mark.parametrize('slicer,ext', [('PrusaSlicer', 'gcode'), ('OrcaSlicer', 'gcode'), ('BambuStudio', 'bgcode')])
def test_bounded_text_facts(tmp_path, monkeypatch, slicer, ext):
    path = tmp_path / ('part.' + ext)
    monkeypatch.setenv('PLATE_CACHE_ROOT', str(tmp_path / 'cache'))
    comments = (f'; generated by {slicer} 2.5.1\n; filament_type = PLA;PETG\n; filament_colour = #ffffff;#000000\n'
                + 'G1 X1\n' * MAX_GCODE_HEADER_BYTES + '; filament used [g] = 5.1,2.1\n')
    middle = len(comments) // 2
    data = (comments[:middle] + '\n; total filament weight [g] : 99\n' + comments[middle:]).encode()
    path.write_bytes(data)
    result, reason = facts_result(SimpleNamespace(stored_path=str(path), file_hash=hashlib.sha256(data).hexdigest(), blob_state='present'))
    assert reason is None and result['slicer'] == {'name': slicer, 'version': '2.5.1'}
    plate, = result['plates']
    assert plate['weight_grams'] == pytest.approx(7.2) and plate['warnings'] is None and not plate['has_thumbnail']
    assert [(f['type'], f['color'], f['grams']) for f in plate['filaments']] == [('PLA', '#ffffff', 5.1), ('PETG', '#000000', 2.1)]


def test_binary_refusal_and_bambu_total(tmp_path):
    from modules.models_library.gcode_facts import read_facts
    path = tmp_path / 'part.bgcode'
    path.write_bytes(b'GCDE\x01\x00')
    assert read_facts(path) == ('binary_gcode', None)
    path.write_bytes(b'; total filament weight [g] : 7.25\n')
    assert read_facts(path)[1]['plates'][0]['weight_grams'] == 7.25
    path.write_bytes(b'; filament_type = PLA\nG1\x00\xff')
    assert read_facts(path)[1]['plates'][0]['filaments'][0]['type'] == 'PLA'


@pytest.mark.parametrize('changed,reason', [(True, 'hash_mismatch'), (False, 'parse_refused')])
def test_snapshot_error_is_identified_by_type(tmp_path, monkeypatch, changed, reason):
    from core import print_payload_snapshot as snapshots
    path = tmp_path / 'part.gcode'
    path.write_bytes(b'G1 X1')
    monkeypatch.setenv('PLATE_CACHE_ROOT', str(tmp_path / 'cache'))
    def refuse(*args):
        if changed:
            raise snapshots.PayloadChanged('different bytes')
        raise snapshots.PayloadUnavailable('unchanged file is unreadable')
    monkeypatch.setattr(snapshots, 'stage_payload', refuse)
    row = SimpleNamespace(stored_path=str(path), file_hash='a' * 64, blob_state='present')
    assert facts_result(row) == (None, reason)


def test_cached_empty_gcode_plate_has_no_slice_facts(tmp_path, monkeypatch):
    from modules.models_library import plate_cache
    path = tmp_path / 'part.gcode'
    path.write_bytes(b'G1 X1\n')
    monkeypatch.setenv('PLATE_CACHE_ROOT', str(tmp_path / 'cache'))
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    plate_cache.store(digest, {'slicer': None, 'plates': [{
        'index': 1, 'warnings': None, 'thumbnail': None, 'layer_height': None,
        'print_time_seconds': None, 'weight_grams': None, 'filaments': [],
    }]})
    row = SimpleNamespace(stored_path=str(path), file_hash=digest, blob_state='present')
    assert facts_result(row) == (None, 'no_slicer_facts')
