"""Server-side enforcement of the Settings > Permissions matrix (spec permissions-enforcement.md).

Completeness: core.rbac_routes maps every action key to routes, every mapped
route carries the matching require_action / require_page dependency in its
dependant tree, and every write route under /api is mapped or has a
documented exemption.

Behaviour: for every action key, a representative mapped route is called
through the real app (cert-G harness: create_app(), bootstrapped SQLite,
signed Enterprise license, real password login). With the default matrix the
role holding the key gets 2xx and a role without it gets 403; after narrowing
the key the previously allowed role gets 403; after widening it the
previously refused role gets 2xx. The platform superadmin is exempt, so keys
whose default is admin-only are exercised with an organization admin. The
only boundary replaced is the smart-plug driver (no physical plug).
"""
